<?php

namespace App\Services;

/**
 * Generates a self-contained RouterOS 6 configuration for a small PPPoE
 * access router behind a Starlink (or any DHCP) uplink, e.g. an RB750Gr3 in a
 * remote location. Like the other standalone generators it uses no WireGuard,
 * no HotspotFreeRAD RADIUS and no Router/Shop/Tenant record.
 *
 * Bandwidth fairness is plain RouterOS HTB:
 *  - A parent simple queue ("starlink-total") caps all client traffic at 90%
 *    of the entered Starlink speeds, so queueing happens on this router
 *    instead of in Starlink's own buffers.
 *  - Each plan is a PPP profile whose rate-limit becomes the client's dynamic
 *    queue, with parent-queue=starlink-total. Clients never exceed their plan,
 *    and when the uplink is full HTB shares it evenly between active clients.
 *  - Devices on plain LAN ports sit in a child queue using PCQ, which gives
 *    every device its own cap and an equal share.
 *  - FastTrack is removed, since fast-tracked traffic skips the queues.
 *
 * The operator administers the router from the Starlink router's own network
 * (their PC on the Starlink Wi-Fi reaches it through ether1), so there is no
 * separate management port. Clients can neither administer the router nor
 * reach that Starlink network.
 *
 * Clients log in with local PPP secrets added afterwards in Winbox
 * (PPP > Secrets); the script only creates the plans. Targets RouterOS 6.40+.
 */
class StandalonePppoeScriptGenerator
{
    public const PORTS = ['ether2', 'ether3', 'ether4', 'ether5'];

    public const PORT_ROLES = [
        'pppoe' => 'PPPoE clients',
        'lan' => 'Plain LAN (DHCP)',
        'unused' => 'Unused',
    ];

    /** Share of the Starlink speed the parent queue allows, keeping Starlink's own buffers empty. */
    public const UPLINK_HEADROOM = 0.9;

    /**
     * @param  array{
     *     router_identity: string,
     *     wan_port: string,
     *     wan_download_mbps: int|float,
     *     wan_upload_mbps: int|float,
     *     admin_network: string,
     *     port_roles: array<string, string>,
     *     pppoe_network: string,
     *     pppoe_service_name: string,
     *     lan_network: string,
     *     lan_device_download_mbps: int|float,
     *     lan_device_upload_mbps: int|float,
     *     plans: list<array{name: string, download_mbps: int|float, upload_mbps: int|float}>,
     * } $config
     */
    public function generate(array $config): string
    {
        $ports = $this->portsByRole($config['port_roles']);

        $lines = array_merge(
            $this->headerLines($config),
            $this->wanLines($config),
            $ports['lan'] !== [] ? $this->lanLines($config, $ports['lan']) : [],
            $this->queueLines($config, $ports),
            $ports['pppoe'] !== [] ? $this->pppoeLines($config, $ports['pppoe']) : [],
            $this->firewallLines($config, $ports),
            $this->footerLines($config, $ports),
        );

        return implode("\n", $lines);
    }

    /**
     * @return array{pppoe: list<string>, lan: list<string>}
     */
    private function portsByRole(array $roles): array
    {
        $grouped = ['pppoe' => [], 'lan' => []];

        foreach (self::PORTS as $port) {
            $role = $roles[$port] ?? 'unused';

            if (isset($grouped[$role])) {
                $grouped[$role][] = $port;
            }
        }

        return $grouped;
    }

    private function headerLines(array $config): array
    {
        return [
            '# Standalone MikroTik PPPoE + fair bandwidth script -- generated by HotspotFreeRAD Script Generator',
            '# RouterOS 6.40 or newer -- check with "/system resource print" and upgrade older routers first.',
            '# '.$config['wan_port'].' = Starlink uplink. Client traffic is capped at '.(int) round(self::UPLINK_HEADROOM * 100).'% of '.$this->mbps($config['wan_download_mbps']).' down / '.$this->mbps($config['wan_upload_mbps']).' up and shared fairly.',
            '# Router admin (Winbox, SSH, web) is allowed only from the Starlink network '.$this->adminCidr($config).' -- e.g. your PC on the Starlink Wi-Fi.',
            '# Run on a router reset with no default configuration, connected over MAC Winbox.',
            '',
            '/system identity set name="'.$this->quote($config['router_identity']).'"',
            '',
        ];
    }

    private function wanLines(array $config): array
    {
        $wan = $config['wan_port'];
        $admin = $this->adminCidr($config);

        return [
            '# Starlink uplink',
            '/interface list add name=WAN comment="Starlink uplink"',
            '/interface list member add list=WAN interface='.$wan,
            '/ip dhcp-client remove [find interface='.$wan.']',
            '/ip dhcp-client add interface='.$wan.' add-default-route=yes use-peer-dns=no disabled=no',
            '/ip dns set allow-remote-requests=yes servers=1.1.1.1,8.8.8.8',
            '/ip firewall nat add chain=srcnat out-interface='.$wan.' action=masquerade',
            '',
            '# Router admin services answer only from the Starlink network',
            '/ip service set www address='.$admin,
            '/ip service set www-ssl address='.$admin,
            '/ip service set winbox address='.$admin,
            '/ip service set ssh address='.$admin,
            '',
        ];
    }

    private function lanLines(array $config, array $lanPorts): array
    {
        $network = $this->networkParts($config['lan_network']);
        $lines = [
            '# Plain LAN ports (DHCP) -- for devices or client routers that do not use PPPoE',
            '/interface bridge add name=bridge-lan comment="Plain LAN clients"',
        ];

        foreach ($lanPorts as $port) {
            $lines[] = '/interface bridge port add bridge=bridge-lan interface='.$port;
        }

        return array_merge($lines, [
            '/ip address add address='.$network['gateway'].' interface=bridge-lan',
            '/ip pool add name=pool-lan ranges='.$network['range'],
            '/ip dhcp-server add name=dhcp-lan interface=bridge-lan address-pool=pool-lan lease-time=1h disabled=no',
            '/ip dhcp-server network add address='.$network['cidr'].' gateway='.$network['host'].' dns-server='.$network['host'],
            '',
        ]);
    }

    /**
     * The parent queue must exist before any PPP profile names it as parent-queue.
     */
    private function queueLines(array $config, array $ports): array
    {
        $totalLimit = $this->rate($config['wan_upload_mbps'], self::UPLINK_HEADROOM).'/'.$this->rate($config['wan_download_mbps'], self::UPLINK_HEADROOM);

        $lines = [
            '# Fair bandwidth: one parent queue for the whole Starlink link (max-limit is upload/download).',
            '# Every PPPoE client queue and the LAN device queue hang under it, so the link is shared evenly when full.',
            '/ip firewall filter remove [find action=fasttrack-connection]',
            '/queue simple add name=starlink-total target='.implode(',', $this->clientNetworks($config, $ports)).' max-limit='.$totalLimit.' comment="Starlink capacity shared by all clients"',
        ];

        if ($ports['lan'] !== []) {
            $lan = $this->networkParts($config['lan_network']);
            $lines[] = '/queue type add name=pcq-lan-download kind=pcq pcq-classifier=dst-address pcq-rate='.$this->rate($config['lan_device_download_mbps']);
            $lines[] = '/queue type add name=pcq-lan-upload kind=pcq pcq-classifier=src-address pcq-rate='.$this->rate($config['lan_device_upload_mbps']);
            $lines[] = '/queue simple add name=lan-devices parent=starlink-total target='.$lan['cidr'].' queue=pcq-lan-upload/pcq-lan-download max-limit='.$totalLimit.' comment="Each LAN device capped at '.$this->mbps($config['lan_device_download_mbps']).' down / '.$this->mbps($config['lan_device_upload_mbps']).' up, shared equally"';
        }

        $lines[] = '';

        return $lines;
    }

    private function pppoeLines(array $config, array $pppoePorts): array
    {
        $network = $this->networkParts($config['pppoe_network']);
        $lines = [
            '# PPPoE server',
            '/interface bridge add name=bridge-pppoe comment="PPPoE clients"',
        ];

        foreach ($pppoePorts as $port) {
            $lines[] = '/interface bridge port add bridge=bridge-pppoe interface='.$port;
        }

        $lines[] = '/ip pool add name=pool-pppoe ranges='.$network['range'];
        $lines[] = '';
        $lines[] = '# Plans: rate-limit is upload/download as seen from the client. Each client gets its own queue under starlink-total.';

        foreach ($config['plans'] as $plan) {
            $lines[] = '/ppp profile add name="'.$this->quote(trim($plan['name'])).'" local-address='.$network['host'].' remote-address=pool-pppoe dns-server='.$network['host']
                .' rate-limit='.$this->rate($plan['upload_mbps']).'/'.$this->rate($plan['download_mbps'])
                .' parent-queue=starlink-total only-one=yes change-tcp-mss=yes';
        }

        $defaultPlan = $this->quote(trim($config['plans'][0]['name']));

        $lines[] = '';
        $lines[] = '/interface pppoe-server server add service-name="'.$this->quote($config['pppoe_service_name']).'" interface=bridge-pppoe default-profile="'.$defaultPlan.'" authentication=pap,chap,mschap1,mschap2 one-session-per-host=yes keepalive-timeout=60 disabled=no';
        $lines[] = '';

        return $lines;
    }

    private function firewallLines(array $config, array $ports): array
    {
        $admin = $this->adminCidr($config);
        $clientNetworks = $this->clientNetworks($config, $ports);

        $lines = [
            '# Firewall: admin only from the Starlink network, clients get DNS only, nothing unsolicited from the internet',
            '/ip firewall filter add chain=input connection-state=established,related action=accept',
            '/ip firewall filter add chain=input connection-state=invalid action=drop',
            '/ip firewall filter add chain=input protocol=icmp action=accept',
            '/ip firewall filter add chain=input in-interface='.$config['wan_port'].' src-address='.$admin.' action=accept comment="Router admin from the Starlink network (your PC)"',
            '/ip firewall filter add chain=input protocol=udp dst-port=67 in-interface-list=!WAN action=accept comment="DHCP requests from local networks"',
        ];

        foreach ($clientNetworks as $cidr) {
            $lines[] = '/ip firewall filter add chain=input src-address='.$cidr.' protocol=udp dst-port=53 action=accept comment="Client DNS"';
            $lines[] = '/ip firewall filter add chain=input src-address='.$cidr.' protocol=tcp dst-port=53 action=accept comment="Client DNS"';
        }

        $lines[] = '/ip firewall filter add chain=input action=drop comment="Drop all other traffic to the router"';
        $lines[] = '/ip firewall filter add chain=forward connection-state=established,related action=accept';
        $lines[] = '/ip firewall filter add chain=forward connection-state=invalid action=drop';

        foreach ($clientNetworks as $cidr) {
            $lines[] = '/ip firewall filter add chain=forward src-address='.$cidr.' dst-address='.$admin.' action=drop comment="Clients cannot reach your PC or the Starlink router settings"';
        }

        $lines[] = '/ip firewall filter add chain=forward in-interface-list=WAN connection-nat-state=!dstnat action=drop comment="Block unsolicited traffic from Starlink"';
        $lines[] = '';

        return $lines;
    }

    private function footerLines(array $config, array $ports): array
    {
        if ($ports['pppoe'] === []) {
            return [];
        }

        $examplePlan = $this->quote(trim($config['plans'][0]['name']));

        return [
            '# Next: add each PPPoE client in Winbox (PPP > Secrets) with one of the plans above, e.g.:',
            '# /ppp secret add name=client1 password=ChangeMe service=pppoe profile="'.$examplePlan.'"',
        ];
    }

    /**
     * @return list<string>
     */
    private function clientNetworks(array $config, array $ports): array
    {
        $networks = [];
        if ($ports['pppoe'] !== []) {
            $networks[] = $this->networkParts($config['pppoe_network'])['cidr'];
        }
        if ($ports['lan'] !== []) {
            $networks[] = $this->networkParts($config['lan_network'])['cidr'];
        }

        return $networks;
    }

    private function adminCidr(array $config): string
    {
        return trim($config['admin_network']);
    }

    /**
     * Mbps as a RouterOS rate, in whole kbps so fractions (e.g. 13.5M) stay exact.
     */
    private function rate(int|float|string $mbps, float $factor = 1.0): string
    {
        $kbps = (int) round(((float) $mbps) * 1000 * $factor);

        return $kbps % 1000 === 0 ? intdiv($kbps, 1000).'M' : $kbps.'k';
    }

    private function mbps(int|float|string $mbps): string
    {
        return rtrim(rtrim(number_format((float) $mbps, 2, '.', ''), '0'), '.').' Mbps';
    }

    /**
     * @return array{gateway: string, host: string, cidr: string, range: string}
     */
    private function networkParts(string $baseCidr): array
    {
        [$host] = explode('/', trim($baseCidr));
        $octets = explode('.', $host);
        $prefix = implode('.', array_slice($octets, 0, 3));

        return [
            'gateway' => $host.'/24',
            'host' => $host,
            'cidr' => $prefix.'.0/24',
            'range' => $prefix.'.10-'.$prefix.'.254',
        ];
    }

    /**
     * Escapes a value for a RouterOS double-quoted string, where \, " and $ are all special.
     */
    private function quote(?string $value): string
    {
        return str_replace(['\\', '"', '$'], ['\\\\', '\"', '\$'], (string) $value);
    }
}
